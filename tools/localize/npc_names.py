def translate(name):
    if name in EXACT:
        return EXACT[name]
    if name.startswith("GM_"):
        suffix = name[3:]
        return "管理员_" + GM_ITEM.get(suffix, name)
    if "_" in name:
        title, given = name.split("_", 1)
        if title in TITLE and given in GIVEN:
            return TITLE[title] + "_" + GIVEN[given]
        if title in TITLE and given in GM_ITEM:
            return TITLE[title] + "_" + GM_ITEM[given]
        if title in TITLE:
            return TITLE[title] + "_" + given
    return None
